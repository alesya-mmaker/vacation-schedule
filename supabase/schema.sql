-- Схема базы «График отпусков».
-- Запускать в Supabase → SQL Editor. Скрипт можно запускать повторно:
-- он удаляет таблицы и создаёт их заново (все данные будут потеряны).

drop table if exists outbox, message_templates, rule_results, rules, requests, employees, units cascade;

-- Подразделения: дерево (дирекция → отделение → отдел → секция)
create table units (
  id        bigint generated by default as identity primary key,
  name      text not null,
  type      text not null check (type in ('дирекция', 'отделение', 'отдел', 'секция')),
  parent_id bigint references units(id)
);

-- Сотрудники. Уволенных не удаляем (active = false), чтобы сохранить историю заявок.
create table employees (
  id               bigint generated by default as identity primary key,
  full_name        text not null,
  personnel_number text not null unique,
  role             text not null check (role in ('МПП', 'менеджер секции', 'НО', 'РО', 'ЗАВ', 'ЗТВ', 'ИД', 'РО1')),
  unit_id          bigint not null references units(id),
  manager_id       bigint references employees(id),
  active           boolean not null default true
);

-- Заявления сотрудников
create table requests (
  id                  bigint generated by default as identity primary key,
  employee_id         bigint not null references employees(id),
  type                text not null check (type in ('отпуск', 'без сохранения з/п', 'плановое лечение')),
  start_date          date not null,
  end_date            date not null,
  substitute_id       bigint references employees(id),
  comment             text,
  submitted_at        timestamptz not null default now(),
  status              text not null default 'на рассмотрении'
                      check (status in ('на рассмотрении', 'согласована', 'отклонена', 'согласована как исключение', 'заменена')),
  replaces_request_id bigint references requests(id),
  -- статус до замены: перенос согласованного отпуска проверяется правилом reschedule_notice
  status_before_replace text
                      check (status_before_replace in ('на рассмотрении', 'согласована', 'отклонена', 'согласована как исключение')),
  -- случайный код для ссылки на корректировку (вместо номеров сотрудника и заявки в адресе)
  correction_token    uuid not null unique default gen_random_uuid(),
  hr_comment          text,
  decided_at          timestamptz,
  check (end_date >= start_date),
  -- исключение без комментария HR не сохраняется
  check (status <> 'согласована как исключение' or coalesce(trim(hr_comment), '') <> '')
);

-- Правила проверки. Логика каждого типа (type) — в модуле правил, параметры — здесь.
create table rules (
  id         bigint generated by default as identity primary key,
  name       text not null,
  type       text not null,
  params     jsonb not null default '{}'::jsonb,
  severity   text not null check (severity in ('нарушение', 'предупреждение', 'информация')),
  applies_to text[] not null default array['отпуск', 'без сохранения з/п', 'плановое лечение'],
  enabled    boolean not null default true,
  source     text not null,
  sort_order int not null default 0
);

-- Результаты проверки: по строке на пару «заявка × правило». Пересчитываются приложением.
create table rule_results (
  request_id        bigint not null references requests(id) on delete cascade,
  rule_id           bigint not null references rules(id) on delete cascade,
  passed            boolean not null,
  possible_conflict boolean not null default false, -- пересечение с заявкой «на рассмотрении»
  message           text not null,
  primary key (request_id, rule_id)
);

-- Шаблоны сообщений. Подстановки: {ФИО}, {даты}, {причина}, {ссылка}
create table message_templates (
  id   bigint generated by default as identity primary key,
  kind text not null unique check (kind in ('отказ', 'согласование', 'исключение')),
  text text not null
);

-- Исходящие: сообщения сотрудникам (реальной отправки в прототипе нет)
create table outbox (
  id          bigint generated by default as identity primary key,
  employee_id bigint not null references employees(id),
  request_id  bigint references requests(id),
  kind        text not null check (kind in ('отказ', 'согласование', 'исключение')),
  text        text not null,
  sent_at     timestamptz not null default now()
);

